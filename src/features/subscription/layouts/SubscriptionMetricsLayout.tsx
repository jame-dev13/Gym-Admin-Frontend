import { RefreshBtn } from "@/components/buttons/Buttons";
import { Navbar } from "@/components/navbar/Navbar";
import { SubscriptionChartsSkeleton } from "@/features/subscription/components/SubscriptionChartsSkeleton";
import { SubscriptionMetricsSectionHeader } from "@/features/subscription/components/SubscriptionMetricsSectionHeader";
import { SubscriptionResumeCardsSkeleton } from "@/features/subscription/components/SubscriptionResumeCardsSkeleton";
import { useGetSubscriptionsAnnualResume } from "@/features/subscription/hooks/useFetchSubscriptionMetrics";
import {
  getSubscriptionMetricsNavbarConfig,
  getSubscriptionMetricsSections,
} from "@/features/subscription/services/subscription-metrics-layout-sections";
import { BarChart3 } from "lucide-react";
import { lazy, Suspense } from "react";

const SubscriptionResumeCards = lazy(() =>
  import("@/features/subscription/components/SubscriptionResumeCards").then(
    (mod) => ({ default: mod.SubscriptionResumeCards }),
  ),
);

const SubscriptionCountDistributionChart = lazy(() =>
  import("@/features/subscription/components/SubscriptionCountDistributionChart").then(
    (mod) => ({ default: mod.SubscriptionCountDistributionChart }),
  ),
);

const SubscriptionWorthDistributionChart = lazy(() =>
  import("@/features/subscription/components/SubscriptionWorthDistributionChart").then(
    (mod) => ({ default: mod.SubscriptionWorthDistributionChart }),
  ),
);

const ERROR_MESSAGE = "The subscription metrics could not be loaded.";

const [summarySection, distributionSection, worthSection] =
  getSubscriptionMetricsSections();

export const SubscriptionMetricsLayout = () => {
  const { data, error, isPending, isRefetching, refetch } =
    useGetSubscriptionsAnnualResume();

  const handleRefetch = async () => {
    try {
      void (await refetch());
    } catch {
      console.error("Error refetching subscription metrics:");
    }
  };

  const content = data?.data.content;
  const membershipResume = content?.membershipResume;
  const isBusy = isPending || isRefetching;
  const statusLabel = isPending
    ? "Loading metrics…"
    : isRefetching
      ? "Refreshing metrics…"
      : "Current snapshot";
  const errorMessage =
    error && !content ? (error.message ?? error.error ?? ERROR_MESSAGE) : null;

  return (
    <section
      className="relative flex h-full min-h-0 w-full flex-col gap-6 overflow-y-auto overscroll-contain pr-2 [scrollbar-color:var(--color-border)_transparent] [scrollbar-width:thin] [&::-webkit-scrollbar]:w-2 [&::-webkit-scrollbar-track]:bg-transparent [&::-webkit-scrollbar-thumb]:rounded-full [&::-webkit-scrollbar-thumb]:bg-border"
      aria-labelledby="subscription-metrics-heading"
    >
      <Navbar
        {...getSubscriptionMetricsNavbarConfig()}
        className="backdrop-blur-sm bg-surface/90"
      />

      <div className="flex min-h-0 flex-1 flex-col gap-6 pb-2">
        <header className="flex flex-col gap-4 xl:flex-row xl:items-end xl:justify-between">
          <div className="flex flex-col gap-2">
            <span className="inline-flex w-fit items-center gap-2 rounded-full border border-accent/30 bg-accent/10 px-3 py-1 text-xs font-semibold uppercase tracking-wider text-accent">
              <BarChart3 size={14} aria-hidden="true" />
              Subscription metrics
            </span>
            <h1
              id="subscription-metrics-heading"
              className="text-3xl font-bold tracking-tight text-text-primary"
            >
              Subscription performance
            </h1>
            <p className="max-w-2xl text-sm leading-relaxed text-text-secondary">
              Review the annual membership summary, plan distribution, and the
              value generated by each subscription plan.
            </p>
          </div>

          <div className="flex items-center gap-3 self-start xl:self-auto">
            <p className="text-[10px] font-semibold uppercase tracking-[0.2em] text-text-tertiary">
              {statusLabel}
            </p>
            <RefreshBtn
              label="Refresh subscription metrics"
              disabled={isBusy}
              cooldownMs={10_000}
              onClick={handleRefetch}
            />
          </div>
        </header>

        {errorMessage ? (
          <div
            role="alert"
            className="flex flex-col gap-4 rounded-2xl border border-danger/30 bg-danger/10 p-5 text-sm text-danger"
          >
            <p>{errorMessage}</p>
            <div className="flex justify-end">
              <RefreshBtn
                label="Retry loading subscription metrics"
                onClick={handleRefetch}
              />
            </div>
          </div>
        ) : (
          <>
            <section
              id={summarySection.id}
              aria-labelledby={summarySection.headingId}
              className="flex scroll-mt-24 flex-col gap-3"
            >
              <SubscriptionMetricsSectionHeader {...summarySection} />

              <Suspense fallback={<SubscriptionResumeCardsSkeleton />}>
                <SubscriptionResumeCards
                  membershipCount={membershipResume?.membershipCount}
                  netWorth={membershipResume?.netWorthDistribution.netWorth}
                  topMembership={content?.topMembership}
                />
              </Suspense>
            </section>

            <section
              id={distributionSection.id}
              aria-labelledby={distributionSection.headingId}
              className="flex scroll-mt-24 flex-col gap-3"
            >
              <SubscriptionMetricsSectionHeader {...distributionSection} />

              <Suspense fallback={<SubscriptionChartsSkeleton />}>
                <SubscriptionCountDistributionChart
                  distribution={membershipResume?.countDistribution}
                />
              </Suspense>
            </section>

            <section
              id={worthSection.id}
              aria-labelledby={worthSection.headingId}
              className="flex scroll-mt-24 flex-col gap-3"
            >
              <SubscriptionMetricsSectionHeader {...worthSection} />

              <Suspense fallback={<SubscriptionChartsSkeleton />}>
                <SubscriptionWorthDistributionChart
                  distribution={membershipResume?.netWorthDistribution}
                />
              </Suspense>
            </section>
          </>
        )}
      </div>
    </section>
  );
};
